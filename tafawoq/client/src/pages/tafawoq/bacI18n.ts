export const BAC_STRINGS: Record<Lang, BacStrings> = { ar, fr, en };

export function useB(): BacStrings {
  return BAC_STRINGS[useLang()];
}

/** Translated message for a server error (access rules, subscription, …). */
export function bacError(b: BacStrings, error: { message: string } | null | undefined): string {
  if (!error) return b.errors.generic;
  if (b.errors[error.message]) return b.errors[error.message];
  if (/fetch|network|Failed to/i.test(error.message)) return b.errors.network;
  return b.errors.generic;
}

export function formatDate(value: Date | string | null | undefined, lang: Lang) {
  if (!value) return "—";
  const date = typeof value === "string" ? new Date(value) : value;
  return date.toLocaleDateString(lang === "ar" ? "ar-DZ" : lang === "fr" ? "fr-DZ" : "en-GB", { year: "numeric", month: "long", day: "numeric" });
}
