export const STRINGS: Record<Lang, TafawoqStrings> = { ar, fr, en };

function storedLang(): Lang {
  try {
    const value = localStorage.getItem("nourix-language");
    return value === "fr" || value === "en" ? value : "ar";
  } catch {
    return "ar";
  }
}

export function useTafawoqLang() {
  const [lang, setLangState] = useState<Lang>(storedLang);
  const setLang = useCallback((next: Lang) => {
    setStoredLanguage(next);
    setLangState(next);
  }, []);
  return { lang, setLang, t: STRINGS[lang], dir: lang === "ar" ? ("rtl" as const) : ("ltr" as const) };
}


const StringsContext = createContext<TafawoqStrings>(ar);
const LangContext = createContext<Lang>("ar");

export function StringsProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  return createElement(
    LangContext.Provider,
    { value: lang },
    createElement(StringsContext.Provider, { value: STRINGS[lang] }, children)
  );
}

export function useLang(): Lang {
  return useContext(LangContext);
}

export function useT(): TafawoqStrings {
  return useContext(StringsContext);
}

/**
 * Wraps curriculum content (skills, explanations, exercises, tutor text) so
 * it keeps its own language direction inside an interface in another one.
 */
export function Content({ children, as = "div", className }: { children: ReactNode; as?: "div" | "span"; className?: string }) {
  return createElement(as, { dir: "rtl", lang: "ar", className }, children);
}
