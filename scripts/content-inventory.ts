// Prints the real content inventory (per stream and subject) as Markdown:
//   npx tsx scripts/content-inventory.ts > docs/CONTENT_INVENTORY.md
// Counts come from the lesson catalogue; review status lives in the database
// and is shown in the admin panel (Content → pedagogical review).
import { contentInventory } from "../server/tafawoq/contentInventory";

const rows = contentInventory();
const out: string[] = [];
out.push("# Content inventory (generated)");
out.push("");
out.push(`Generated by \`scripts/content-inventory.ts\` on ${new Date().toISOString().slice(0, 10)} from the lesson catalogue.`);
out.push("");
out.push("**Read this carefully:** a subject with lessons is *not* a subject whose official BAC programme is covered.");
out.push("Coverage of the ministry programme has not been measured: it needs a teacher of the subject to map these lessons");
out.push("against the official programme. No lesson has been pedagogically approved by a teacher unless the admin panel");
out.push("(Content → pedagogical review) says so; automated tests check answers and code, not teaching quality.");
out.push("");
out.push("Question kinds: *mcq* = multiple choice (marked automatically); *short* = short answer (number, expression or");
out.push("exact word, marked automatically, with an AI second opinion — flagged as such — for unusual forms);");
out.push("*generators* = templates producing unlimited computed exercises; *problems* = multi-part BAC-style exercises.");
out.push("Essays and free writing are never marked automatically (topic bank answers are self-assessed against a model answer).");
out.push("");
let stream = "";
for (const row of rows) {
  if (row.stream !== stream) {
    stream = row.stream;
    out.push(`## Stream: ${stream}`);
    out.push("");
    out.push("| Subject | Role | Lessons | Skills | MCQ | Short | Generators | Problems |");
    out.push("|---|---|---:|---:|---:|---:|---:|---:|");
  }
  const sum = (field: "skills" | "mcq" | "short" | "generators" | "problems") => row.lessons.reduce((total, lesson) => total + lesson[field], 0);
  out.push(
    `| ${row.subject} | ${row.role} | ${row.lessons.length || "**none**"} | ${sum("skills")} | ${sum("mcq")} | ${sum("short")} | ${sum("generators")} | ${sum("problems")} |`
  );
  if (rows[rows.indexOf(row) + 1]?.stream !== stream) out.push("");
}
out.push("## Lessons");
out.push("");
const seen = new Set<string>();
for (const row of rows) {
  for (const lesson of row.lessons) {
    if (seen.has(lesson.key)) continue;
    seen.add(lesson.key);
    out.push(`- \`${lesson.key}\` (${lesson.subject}) — ${lesson.title}: ${lesson.skills} skills, ${lesson.mcq + lesson.short} bank questions, ${lesson.generators} generators, ${lesson.problems} problems`);
  }
}
console.log(out.join("\n"));
